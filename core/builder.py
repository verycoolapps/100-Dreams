# 100 DREAMS — Automatic HTML construction
import base64
import datetime
import html
import json
import os
import shutil

ADDON_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ADDON_DIR, "web")
VERSION = "1.0.0"
SINGLE_LIMIT = 48 * 1024 * 1024
MARKER = ".100dreams"


def _read(name, mode="r"):
    with open(os.path.join(WEB, name), mode, **({} if "b" in mode else {"encoding": "utf-8"})) as f:
        return f.read()


def _script_safe(text):
    return text.replace("</", "<\\/").replace("<!--", "<\\!--")


def _json_for_html(obj):
    return _script_safe(json.dumps(obj, ensure_ascii=False, separators=(",", ":")))


def clean_for_json(data):
    out = {k: v for k, v in data.items() if not k.startswith("_")}
    out["objects"] = [{k: v for k, v in o.items() if not k.startswith("_")} for o in data["objects"]]
    env = dict(out.get("environment", {}))
    env.pop("hdriPath", None); env.pop("hdriImage", None)
    out["environment"] = env
    return out


def choose_mode(requested, glb_size, env_size):
    if requested == "SINGLE":
        return "single"
    if requested == "PACKAGE":
        return "package"
    return "single" if glb_size + env_size <= SINGLE_LIMIT else "package"


def build(stage_dir, data, glb_path, env_file, mode, preset):
    """Assemble the website into stage_dir. Returns the index.html path."""
    template = _read("template.html")
    css = _read("style.css")
    runtime = _read("runtime.bundle.js")
    data = clean_for_json(data)
    data["defaultPreset"] = preset
    data["exportedAt"] = datetime.datetime.now().isoformat(timespec="seconds")
    data["generator"] = f"100 DREAMS {VERSION}"
    glb_b64 = env_b64 = ""
    os.makedirs(os.path.join(stage_dir, "data"), exist_ok=True)
    if mode == "single":
        with open(glb_path, "rb") as f:
            glb_b64 = base64.b64encode(f.read()).decode("ascii")
        if env_file:
            with open(env_file, "rb") as f:
                env_b64 = base64.b64encode(f.read()).decode("ascii")
        data["glbUrl"] = None
    else:
        models = os.path.join(stage_dir, "assets", "models")
        os.makedirs(models, exist_ok=True)
        shutil.copyfile(glb_path, os.path.join(models, "world.glb"))
        data["glbUrl"] = "assets/models/world.glb"
        if env_file:
            envdir = os.path.join(stage_dir, "assets", "environments")
            os.makedirs(envdir, exist_ok=True)
            name = os.path.basename(env_file)
            shutil.copyfile(env_file, os.path.join(envdir, name))
            data["environment"]["hdriUrl"] = f"assets/environments/{name}"
        write_launchers(stage_dir)
    page = (template.replace("{{CSS}}", css)
            .replace("{{TITLE}}", html.escape(data["name"]))
            .replace("{{DESCRIPTION}}", html.escape(f"Dunia 3D interaktif “{data['name']}” dengan 100 game, dibuat otomatis dari Blender oleh 100 DREAMS."))
            .replace("{{VERSION}}", VERSION)
            .replace("{{DATA}}", _json_for_html(data))
            .replace("{{GLB}}", glb_b64).replace("{{ENV}}", env_b64)
            .replace("{{RUNTIME}}", _script_safe(runtime)))
    index = os.path.join(stage_dir, "index.html")
    with open(index, "w", encoding="utf-8") as f:
        f.write(page)
    with open(os.path.join(stage_dir, "data", "world.json"), "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    with open(os.path.join(stage_dir, MARKER), "w", encoding="utf-8") as f:
        f.write(f"Generated by 100 DREAMS {VERSION}. This folder may be replaced on regenerate.\n")
    write_readme(stage_dir, data, mode)
    return index


def write_launchers(stage_dir):
    py = '''import http.server, socketserver, webbrowser, os, functools
os.chdir(os.path.dirname(os.path.abspath(__file__)))
H = functools.partial(http.server.SimpleHTTPRequestHandler, directory=".")
with socketserver.TCPServer(("127.0.0.1", 0), H) as s:
    url = f"http://127.0.0.1:{s.server_address[1]}/index.html"
    print("100 DREAMS world running at", url, "- press Ctrl+C to stop")
    webbrowser.open(url)
    s.serve_forever()
'''
    with open(os.path.join(stage_dir, "start_world.py"), "w", encoding="utf-8") as f:
        f.write(py)
    with open(os.path.join(stage_dir, "Start World (Windows).bat"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write('@echo off\ncd /d "%~dp0"\nwhere py >nul 2>nul && (py start_world.py) || (python start_world.py)\npause\n')
    p = os.path.join(stage_dir, "Start World (macOS).command")
    with open(p, "w", encoding="utf-8") as f:
        f.write('#!/bin/sh\ncd "$(dirname "$0")"\npython3 start_world.py\n')
    try:
        os.chmod(p, 0o755)
    except OSError:
        pass


def write_readme(stage_dir, data, mode):
    howto = ("Buka <code>index.html</code> langsung di browser. Semua aset sudah tertanam di file itu." if mode == "single" else
             "Paket ini memuat aset terpisah, jadi browser butuh server lokal. Jalankan <code>Start World</code> sesuai sistem operasi, "
             "atau <code>python3 start_world.py</code>, atau tombol OPEN HTML WORLD di Blender. Untuk dipublikasikan, unggah seluruh folder ke hosting statis apa pun (Netlify, GitHub Pages, Vercel).")
    s = data.get("stats", {})
    body = f"""<!doctype html><html lang="id"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Cara membuka · {html.escape(data['name'])}</title>
<style>body{{font:16px/1.6 system-ui,sans-serif;max-width:720px;margin:48px auto;padding:0 20px;color:#1d1f3a}}h1{{font-size:28px}}code{{background:#eef0ff;padding:2px 6px;border-radius:6px}}</style>
<h1>{html.escape(data['name'])}</h1>
<p>Dunia ini dibuat otomatis oleh 100 DREAMS dari scene “{html.escape(data['scene'])}” (Blender {html.escape(data['blender'])}).</p>
<h2>Cara membuka</h2><p>{howto}</p>
<h2>Isi</h2><p>{s.get('objects', 0)} objek, {s.get('triangles', 0):,} segitiga, {s.get('materials', 0)} material, {len(data.get('animations', []))} animasi, 100 game.</p>
<h2>Kebutuhan</h2><p>Browser dengan WebGL2: Chrome, Edge, Firefox, atau Safari versi terbaru. Font web dimuat dari Google Fonts bila online; tanpa internet, font sistem dipakai.</p>
<p>Laporan pemeriksaan otomatis ada di <code>report.html</code>.</p></html>"""
    with open(os.path.join(stage_dir, "README.html"), "w", encoding="utf-8") as f:
        f.write(body)
